import { readFileSync, writeFileSync } from 'node:fs'

// The released profile schema owns SecretRefs and credential constraints.
const upstream = JSON.parse(readFileSync(new URL('../tools/node_modules/@knowttl/mg-axi/axi-credential.schema.json', import.meta.url), 'utf8'))
const { version } = JSON.parse(readFileSync(new URL('../tools/node_modules/@knowttl/mg-axi/package.json', import.meta.url), 'utf8'))
const schema = { ...upstream,
  title: `@knowttl/mg-axi ${version} headless application profile`,
  description: 'Application projection of the published axi-credential.schema.json; generated by scripts/mg-headless-schema.mjs. Live consent unverified.',
  allOf: [{ required: ['mode'], properties: { mode: { const: 'application' } } }],
}
const destination = new URL('../tools/inventories/mg-axi-headless.schema.json', import.meta.url)
const contents = JSON.stringify(schema, null, 2) + '\n'
if (process.argv.includes('--write')) writeFileSync(destination, contents)
else if (readFileSync(destination, 'utf8') !== contents) throw new Error('Headless schema out of date')
console.log(`schema: mg-axi headless application profile ${version}`)
