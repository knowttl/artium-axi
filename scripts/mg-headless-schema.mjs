import { readFileSync, writeFileSync } from 'node:fs'

// This local projection describes the pinned application-profile validator.
// Upstream inventory/schema.json describes Graph operations, not profiles.
const object = (properties, required = Object.keys(properties)) => ({ type: 'object', additionalProperties: false, properties, required })
const uuid = { type: 'string', pattern: '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$' }
const env = { type: 'string', pattern: '^[A-Za-z_][A-Za-z0-9_]*$' }
const path = { type: 'string', pattern: /\S/.source }
const reference = (provider, fields, required) => object({ provider: { const: provider }, key: uuid, ...fields }, ['provider', 'key', ...required])
const thumbprint = { type: 'string', pattern: '^[0-9a-fA-F]{40}$' }
const schema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  title: '@knowttl/mg-axi 0.1.4 headless application profile',
  description: 'Local projection of dist/profiles.js; generated by scripts/mg-headless-schema.mjs. Live consent unverified.',
  ...object({
    mode: { const: 'application' }, tenantId: uuid, clientId: uuid, cloud: { const: 'commercial' },
    preview: { type: 'boolean' }, allowDeviceCode: { const: false },
    enabledPacks: { type: 'array', items: { const: 'entra' }, uniqueItems: true },
    sensitiveAreas: { type: 'array', maxItems: 0 },
    credentialRef: { oneOf: [
      reference('client-secret', { secretEnv: env }, ['secretEnv']),
      reference('client-secret', { secretFile: path }, ['secretFile']),
      reference('certificate', { thumbprint, keyEnv: env }, ['thumbprint', 'keyEnv']),
      reference('certificate', { thumbprint, keyFile: path }, ['thumbprint', 'keyFile']),
      reference('certificate', { thumbprint }, ['thumbprint']),
      reference('federated', { tokenFileEnv: env }, []),
    ] },
    writes: object({ allowWrites: { type: 'boolean' }, operations: { type: 'array', minItems: 1, maxItems: 64,
      items: { type: 'string', minLength: 1, maxLength: 256 } } }),
  }, ['mode', 'tenantId', 'clientId', 'cloud', 'preview', 'allowDeviceCode', 'enabledPacks', 'sensitiveAreas', 'credentialRef']),
}
const destination = new URL('../tools/inventories/mg-axi-headless.schema.json', import.meta.url)
const contents = JSON.stringify(schema, null, 2) + '\n'
if (process.argv.includes('--write')) writeFileSync(destination, contents)
else if (readFileSync(destination, 'utf8') !== contents) throw new Error('Headless schema out of date')
console.log('schema: mg-axi headless application profile 0.1.4')
